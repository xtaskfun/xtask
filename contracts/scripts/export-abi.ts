import fs from "fs";
import path from "path";

// Writes the escrow ABI into the web app so wagmi gets full type inference.
const artifact = require("../artifacts/contracts/XTaskEscrow.sol/XTaskEscrow.json");
const out = path.join(__dirname, "..", "..", "src", "lib", "escrow-abi.ts");
